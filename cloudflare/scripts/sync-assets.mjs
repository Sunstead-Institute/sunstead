// 2. Deterministic glob matcher (must match globMatches in src/core.ts)
function segmentMatches(pat, seg) {
  const dp = Array.from({ length: pat.length + 1 }, () =>
    Array(seg.length + 1).fill(false)
  );
  dp[0][0] = true;
  for (let i = 1; i <= pat.length; i++) {
    if (pat[i - 1] === "*") dp[i][0] = dp[i - 1][0];
  }
  for (let i = 1; i <= pat.length; i++) {
    for (let j = 1; j <= seg.length; j++) {
      if (pat[i - 1] === "*") {
        dp[i][j] = dp[i - 1][j] || dp[i][j - 1];
      } else if (pat[i - 1] === "?" || pat[i - 1] === seg[j - 1]) {
        dp[i][j] = dp[i - 1][j - 1];
      }
    }
  }
  return dp[pat.length][seg.length];
}

function matchSegments(pat, p) {
  if (pat.length === 0 && p.length === 0) return true;
  if (pat[0] === "**") {
    return matchSegments(pat.slice(1), p) || (p.length > 0 && matchSegments(pat, p.slice(1)));
  }
  if (pat.length > 0 && p.length > 0) {
    return segmentMatches(pat[0], p[0]) && matchSegments(pat.slice(1), p.slice(1));
  }
  return false;
}

function globMatches(pattern, relPath) {
  const patSegs = pattern.split("/").filter(Boolean);
  const pathSegs = relPath.split("/").filter(Boolean);
  return matchSegments(patSegs, pathSegs);
}

function walkFiles(dir, base = dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if ([".git", "target", ".lake"].includes(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkFiles(full, base, acc);
    } else if (entry.isFile()) {
      acc.push({
        rel: path.relative(base, full).split(path.sep).join("/"),
        abs: full,
      });
    }
  }
  return acc;
}

function computeFilesSha256(files) {
  const sorted = [...files].sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0));
  const hash = crypto.createHash("sha256");
  for (const f of sorted) {
    const bytes = fs.readFileSync(f.abs);
    const lenBuf = Buffer.alloc(8);
    lenBuf.writeBigUInt64LE(BigInt(bytes.length));
    hash.update(Buffer.from(f.rel, "utf8"));
    hash.update(Buffer.from([0]));
    hash.update(lenBuf);
    hash.update(Buffer.from([0]));
    hash.update(bytes);
    hash.update(Buffer.from("\n", "utf8"));
  }
  return `sha256:${hash.digest("hex")}`;
}

function computeSpecSha256(missionDir, frozenPaths) {
  const files = walkFiles(missionDir).filter((f) =>
    frozenPaths.some((pat) => globMatches(pat, f.rel))
  );
  return computeFilesSha256(files);
}

function computeSeedTreeSha256(missionDir) {
  return computeFilesSha256(walkFiles(missionDir));
}

const missionsDir = path.join(REPO_ROOT, "missions");
const missionDirs = fs
  .readdirSync(missionsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(missionsDir, d.name, "sunstead.json")))
  .map((d) => d.name)
  .sort();

/**
 * Extract classic Lean verifier contract (`lib_root`, `statement_preamble`, and
 * per-task `module`/`theorem`/`statement`) from a mission's frozen `./verify`.
 * Uses Python's `ast` module for exact literal parsing of triple-quoted strings.
 */
function extractVerifyContract(verifyPath) {
  if (!fs.existsSync(verifyPath)) return null;
  const py = `
import ast, json, sys
src = open(sys.argv[1], "r", encoding="utf-8").read()
tree = ast.parse(src)
vals = {}
for node in tree.body:
    if isinstance(node, ast.Assign):
        for t in node.targets:
            if isinstance(t, ast.Name) and t.id in ("LIB_ROOT", "STATEMENT_PREAMBLE", "TASKS", "FROZEN_FILES"):
                try:
                    vals[t.id] = ast.literal_eval(node.value)
                except Exception:
                    pass
if "LIB_ROOT" not in vals or not isinstance(vals.get("TASKS"), dict):
    print("null")
    sys.exit(0)
tasks = {}
for tid, spec in vals["TASKS"].items():
    if isinstance(spec, dict) and isinstance(spec.get("module"), str) and isinstance(spec.get("theorem"), str):
        tasks[tid] = {
            "module": spec["module"],
            "theorem": spec["theorem"],
            "statement": spec.get("statement", ""),
        }
print(json.dumps({
    "lib_root": vals["LIB_ROOT"],
    "statement_preamble": vals.get("STATEMENT_PREAMBLE", "") or "",
    "frozen_lean_modules": [
        p[:-5].replace("/", ".")
        for p in (vals.get("FROZEN_FILES") or [])
        if isinstance(p, str) and p.endswith(".lean")
    ],
    "tasks": tasks,
}))
`;
  try {
    const out = execFileSync("python3", ["-c", py, verifyPath], { encoding: "utf8" }).trim();
    return out && out !== "null" ? JSON.parse(out) : null;
  } catch {
    return null;
  }
}

const missions = missionDirs.map((dirName) => {
  const fullDir = path.join(missionsDir, dirName);
  const manifest = JSON.parse(fs.readFileSync(path.join(fullDir, "sunstead.json"), "utf8"));
  const spec_sha256 = computeSpecSha256(fullDir, manifest.frozen_paths);
  const seed_tree_sha256 = computeSeedTreeSha256(fullDir);
  const image = (manifest.verifier?.image || "").trim();
  const toolchain = (manifest.verifier?.toolchain || "").trim();
  let verifier_kind;
  if (toolchain) {
    if (toolchain === "leanprover/lean4:v4.36.0") {
      verifier_kind = "lean4";
    } else if (toolchain === "leanprover/lean4:v4.35.0") {
      verifier_kind = "lean4-v4.35.0";
    } else if (toolchain === "leanprover/lean4:v4.31.0") {
      verifier_kind = "lean4-v4.31.0";
    } else {
      throw new Error(`unsupported verifier toolchain in ${dirName}: ${toolchain}`);
    }
  } else if (image.includes("lean4-v4.35.0")) {
    verifier_kind = "lean4-v4.35.0";
  } else if (image.includes("lean4-v4.31.0")) {
    verifier_kind = "lean4-v4.31.0";
  } else if (image.includes("lean4")) {
    verifier_kind = "lean4";
  } else {
    throw new Error(`unsupported verifier image in ${dirName}: ${image} (hub is Lean 4 only)`);
  }
  // Embed readable seed source/config files so `GET /api/missions/:id/tasks/:task/files`
  // serves theorem stubs and frozen specs directly from the Worker without waking containers.
  const seed_files = {};
  for (const f of walkFiles(fullDir).sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0))) {
    if (f.rel === "verify" || f.rel === "sunstead.json") continue;
    seed_files[f.rel] = fs.readFileSync(f.abs, "utf8");
  }
  const verify_contract = extractVerifyContract(path.join(fullDir, "verify"));
  return {
    manifest,
    spec_sha256,
    seed_tree_sha256,
    verifier_kind,
    seed_files,
    ...(verify_contract ? { verify_contract } : {}),
  };
});

fs.writeFileSync(
  path.join(GEN_DIR, "missions.ts"),
  `// Auto-generated by scripts/sync-assets.mjs — do not edit manually.\n` +
    `import type { MissionManifest, MissionVerifyContract, VerifierKind } from "../core";\n\n` +
    `export interface SeedMission {\n` +
    `  manifest: MissionManifest;\n` +
    `  spec_sha256: string;\n` +
    `  seed_tree_sha256?: string;\n` +
    `  verifier_kind: VerifierKind;\n` +
    `  seed_files?: Record<string, string>;\n` +
    `  verify_contract?: MissionVerifyContract;\n` +
    `}\n\n` +
    `export const SEED_MISSIONS: SeedMission[] = ${JSON.stringify(missions, null, 2)};\n`
);

console.log(`Synced ${Object.keys(staticAssets).length} static UI assets and ${missions.length} missions.`);
